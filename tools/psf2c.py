#!/usr/bin/env python3
"""Convert PSF console fonts to a C source file.

The output contains the printable ASCII glyphs (0x20-0x7E) of each font.
Each glyph row uses (width + 7) / 8 bytes. The most significant bit is
the leftmost pixel.

Usage: psf2c.py OUT.c NAME=FONT.psf.gz [NAME=FONT.psf.gz ...]
"""
import gzip
import struct
import sys

FIRST, LAST = 0x20, 0x7E


def load_psf(path):
    """Return (width, height, glyphs, codepoint-to-glyph map)."""
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    umap = {}
    if data[:2] == b"\x36\x04":
        mode, height = data[2], data[3]
        width, count, size, pos = 8, 512 if mode & 1 else 256, height, 4
        glyphs = [data[pos + i * size:pos + (i + 1) * size] for i in range(count)]
        if mode & 6:
            table = data[pos + count * size:]
            glyph, i = 0, 0
            while glyph < count and i + 1 < len(table):
                (u,) = struct.unpack_from("<H", table, i)
                i += 2
                if u == 0xFFFF:
                    glyph += 1
                elif u != 0xFFFE:
                    umap.setdefault(u, glyph)
    elif data[:4] == b"\x72\xb5\x4a\x86":
        _, hsize, flags, count, size, height, width = struct.unpack_from("<7I", data, 4)
        glyphs = [data[hsize + i * size:hsize + (i + 1) * size] for i in range(count)]
        if flags & 1:
            table = data[hsize + count * size:]
            for glyph, entry in enumerate(table.split(b"\xff")[:count]):
                for ch in entry.split(b"\xfe")[0].decode("utf-8", "replace"):
                    umap.setdefault(ord(ch), glyph)
    else:
        sys.exit(f"{path}: not a PSF font")
    return width, height, glyphs, umap


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = [
        "/* Generated by tools/psf2c.py. Do not edit. */",
        "/* Glyphs from Terminus Font, Copyright (c) 2010 Dimitar Toshkov Zhekov.",
        " * Licensed under the SIL Open Font License, Version 1.1. Refer to OFL.txt. */",
        '#include "display.h"',
    ]
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        width, height, glyphs, umap = load_psf(path)
        out.append("")
        out.append(f"/* {path.rsplit('/', 1)[-1]} */")
        out.append(f"static const uint8_t {name}_bits[] = {{")
        for code in range(FIRST, LAST + 1):
            glyph = glyphs[umap.get(code, code)]
            hexes = ", ".join(f"0x{b:02x}" for b in glyph)
            out.append(f"    {hexes}, /* {chr(code)!r} */")
        out.append("};")
        out.append(f"const font_t {name} = {{ {width}, {height}, {name}_bits }};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
